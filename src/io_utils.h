#ifndef IO_UTILS_H
#define IO_UTILS_H

#include <stdbool.h>
#include <stdio.h>

// ============================================================================
// 文件 IO 工具函数
//
// 本头文件提供一组与文件读取和字符串预处理相关的工具函数：
//   - io_read_file  : 一次性读入整个文件
//   - io_read_lines : 按行读文件并回调
//   - io_to_lower   : 字符串原地转小写
//   - io_trim       : 去掉字符串首尾空白
// ============================================================================

// ----------------------------------------------------------------------------
// 读文件到动态分配的字符串
//
// 参数:
//   filename : 要读取的文件路径
//
// 返回值:
//   - 成功: 指向堆上分配的字符串，调用者负责 free()
//   - 失败: NULL（文件不存在 / 打开失败 / 内存分配失败）
//
// 注意: 返回的字符串以 '\0' 结尾
// ----------------------------------------------------------------------------
char* io_read_file(const char *filename);

// ----------------------------------------------------------------------------
// 按行读文件，每行去掉换行符后传给 callback
//
// 参数:
//   filename  : 要读取的文件路径
//   callback  : 每读到一行时调用的回调函数
//               - line      : 当前行内容（已去掉结尾换行符，以 '\0' 结尾）
//               - user_data : 透传的自定义数据指针
//               - 返回值: 返回 false 时提前停止读取，返回 true 继续
//   user_data : 透传给 callback 的自定义数据（可以是 NULL）
//
// 返回值:
//   - true  : 文件成功打开并开始读取（不代表读完，callback 可能提前停止）
//   - false : 文件打开失败
// ----------------------------------------------------------------------------
bool io_read_lines(const char *filename,bool (*callback)(const char *line, void *user_data),void *user_data);

// ----------------------------------------------------------------------------
// 转小写（原地修改）
//
// 参数:
//   s : 要转换的字符串（必须是可写的）
//
// 行为:
//   - 将 s 中所有 ASCII 大写字母（A-Z）转为对应小写（a-z）
//   - 其他字符（小写、数字、标点、多字节字符的字节）保持不变
//   - 直接修改 s 指向的内存，无返回值
//
// 注意:
//   - 这是原地修改，调用后 s 指向的内容已改变
//   - 只处理 ASCII 范围，不做 Unicode/UTF-8 感知的转换
// ----------------------------------------------------------------------------
void io_to_lower(char *s);

// ----------------------------------------------------------------------------
// 去掉字符串首尾空白（原地修改）
//
// 参数:
//   s : 要修剪的字符串（必须是可写的）
//
// 行为:
//   - 去掉 s 开头的所有空白字符（空格、\t、\n、\r、\v、\f）
//   - 去掉 s 结尾的所有空白字符
//   - 中间的有效内容通过 memmove 移到字符串开头
//   - 结果原地保存在 s 中，无返回值
//
// 示例:
//   "  hello  "  ->  "hello"
//   "   "        ->  ""
//   "a b c "     ->  "a b c"
//
// 注意:
//   - 这是原地修改，调用后 s 指向的内容已改变
//   - 只处理首尾空白，字符串中间的空白不受影响
// ----------------------------------------------------------------------------
void io_trim(char *s);

bool is_blank_line(const char *s);

long long get_file_size(const char *path);

#endif